/* ---------------- Ordering game ---------------- */
(() => {
  const root = $('#order');
  if (!root) return;
  const slots = $('#ord-slots'), pool = $('#ord-pool'), msg = $('#ord-msg');
  let next = 0;

  function reset() {
    next = 0;
    slots.innerHTML = PHASES.map((_, i) => `<div class="slot">${arNum(i + 1)}</div>`).join('');
    pool.innerHTML = '';
    shuffle(PHASES.map((p, i) => [p, i])).forEach(([p, i]) => {
      const c = document.createElement('button');
      c.className = 'chip';
      c.textContent = p;
      c.addEventListener('click', () => {
        if (i === next) {
          const slot = slots.children[next];
          slot.classList.add('filled');
          slot.innerHTML = `<span>${arNum(next + 1)}</span>${p}`;
          c.remove();
          next++;
          msg.textContent = next === PHASES.length ? '🎉 ممتاز! الترتيب صح' : `${arNum(next)} / ${arNum(PHASES.length)}`;
        } else {
          c.classList.remove('shake');
          void c.offsetWidth;
          c.classList.add('shake');
        }
      });
      pool.appendChild(c);
    });
    msg.textContent = `٠ / ${arNum(PHASES.length)}`;
  }
  $('#ord-reset').addEventListener('click', reset);
  reset();
})();

/* ---------------- Risk matrix ---------------- */
(() => {
  const root = $('#risk');
  if (!root) return;
  // Levels exactly as the book's matrix: LEVEL[impact][probability], 0 = low.
  const NAMES = ['منخفض جدًا', 'منخفض', 'متوسط', 'مرتفع', 'مرتفع جدًا'];
  const LEVEL = [
    [0, 1, 2],
    [2, 2, 3],
    [2, 3, 4],
  ];
  const AX = ['منخفض', 'متوسط', 'مرتفع'];
  const AXP = ['منخفضة', 'متوسطة', 'مرتفعة'];
  const ADVICE = [
    'أولوية منخفضة جدًا — نراقبه.',
    'أولوية منخفضة.',
    'أولوية متوسطة — حسب السياق والضوابط المتاحة.',
    'أولوية عالية — نعالجه قريب.',
    'أعلى أولوية — نعالجه أولاً! 🔥',
  ];
  const state = { impact: 2, prob: 2 };
  const matrix = $('#rk-matrix');

  function render() {
    let html = '';
    for (let im = 2; im >= 0; im--) {
      html += `<div class="ax">${AX[im]}</div>`;
      for (let pr = 0; pr < 3; pr++) {
        const lv = LEVEL[im][pr];
        const sel = im === state.impact && pr === state.prob ? ' sel' : '';
        html += `<div class="cell lv${lv}${sel}" data-im="${im}" data-pr="${pr}">${NAMES[lv]}</div>`;
      }
    }
    html += '<div></div>' + AXP.map(a => `<div class="ax">${a}</div>`).join('');
    matrix.innerHTML = html;
    $$('.seg', root).forEach(seg => {
      const v = state[seg.dataset.axis];
      $$('button', seg).forEach(b => b.classList.toggle('on', +b.dataset.v === v));
    });
    const lv = LEVEL[state.impact][state.prob];
    $('#rk-out').className = `risk-out lv${lv}`;
    $('#rk-out').innerHTML = `المستوى: <b>${NAMES[lv]}</b><br><span class="text-base">${ADVICE[lv]}</span>`;
  }

  matrix.addEventListener('click', e => {
    const c = e.target.closest('.cell');
    if (!c) return;
    state.impact = +c.dataset.im;
    state.prob = +c.dataset.pr;
    render();
  });
  $$('.seg', root).forEach(seg => seg.addEventListener('click', e => {
    const b = e.target.closest('button');
    if (!b) return;
    state[seg.dataset.axis] = +b.dataset.v;
    render();
  }));
  render();
})();

